/**
 * Busca un producto por código de barras exacto en el Catálogo Maestro Argentino.
 */
export function buscarEnCatalogoMaestro(codigo: string): ProductoMaestro | undefined {
  if (!codigo) return undefined
  const clean = codigo.trim()
  return CATALOGO_MAESTRO_ARGENTINO.find(
    (p) => p.codigo_barras === clean || p.codigo_barras.endsWith(clean) || clean.endsWith(p.codigo_barras)
  )
}

/**
 * Busca productos por coincidencia de texto (descripción o código) en el Catálogo Maestro.
 */
export function buscarPorTextoEnCatalogoMaestro(
  query: string,
  limite = 8
): ProductoMaestro[] {
  if (!query) return []
  const q = query.toLowerCase().trim()
  return CATALOGO_MAESTRO_ARGENTINO.filter((p) => {
    return (
      p.descripcion.toLowerCase().includes(q) ||
      p.codigo_barras.includes(q) ||
      p.categoria_nombre.toLowerCase().includes(q)
    )
  }).slice(0, limite)
}

/**
 * Retorna la lista única de categorías sugeridas contenidas en el catálogo maestro.
 */
export function obtenerCategoriasMaestras(): string[] {
  const set = new Set<string>()
  for (const prod of CATALOGO_MAESTRO_ARGENTINO) {
    if (prod.categoria_nombre) set.add(prod.categoria_nombre)
  }
  return Array.from(set)
}
